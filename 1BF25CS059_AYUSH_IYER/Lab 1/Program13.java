class Program13 {
public static void main(String[] args) {
int positive = 35;
int negative = -8;
System.out.println("35 >> 2 = " + (positive >> 2));
System.out.println("-8 >> 1 = " + (negative >> 1));
int x = 8;
System.out.println("x = " + x);
System.out.println("x << 1 = " + (x << 1));
System.out.println("x >> 1 = " + (x >> 1));
}
}
